#!/bin/bash
# 原始 HTTP 包全链路验证
set +e
echo "################################################################"
echo "## 1. BASELINE: 访问根路径"
echo "################################################################"
curl -sS -i http://127.0.0.1:8800/

echo
echo "################################################################"
echo "## 2. 未授权访问 /api/login (GET, 无任何凭据)"
echo "################################################################"
curl -sS -i -X GET http://127.0.0.1:8800/api/login

echo
echo "################################################################"
echo "## 3. 未授权访问 /api/login (POST 空 body)"
echo "################################################################"
curl -sS -i -X POST http://127.0.0.1:8800/api/login -H "Content-Type: application/json" -d '{}'

echo
echo "################################################################"
echo "## 4. 未授权访问 /api/login (POST 任意错误凭据)"
echo "################################################################"
curl -sS -i -X POST http://127.0.0.1:8800/api/login -H "Content-Type: application/json" -d '{"username":"hacker","password":"wrong"}'

echo
echo "################################################################"
echo "## 5. 旁路：仅 query string 试探"
echo "################################################################"
curl -sS -i 'http://127.0.0.1:8800/api/login?debug=1&raw=1'

